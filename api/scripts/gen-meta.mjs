// Regenerates the CARD_META block in src/index.ts from ../index.html.
// Usage: node scripts/gen-meta.mjs
import fs from "node:fs";
import { cardIds } from "./slug.mjs";
const html = fs.readFileSync(new URL("../../index.html", import.meta.url), "utf8");
const m = html.match(/const CARDS = (\[[\s\S]*?\n\]);/);
const cards = Function("return " + m[1])();
const ids = cardIds(cards);
const meta = {};
cards.forEach((c, i) => meta[ids[i]] = [c[0], c[2], c[3]]);
const block = "// BEGIN CARD_META (generated by scripts/gen-meta.mjs; do not edit by hand)\n" +
  "const CARD_META: Record<string, [dutch: string, russian: string, topic: string]> = " +
  JSON.stringify(meta, null, 1) + ";\n// END CARD_META";
const p = new URL("../src/index.ts", import.meta.url);
const src = fs.readFileSync(p, "utf8");
fs.writeFileSync(p, src.replace(/\/\/ BEGIN CARD_META[\s\S]*?\/\/ END CARD_META/, block));
console.log("CARD_META:", ids.length, "cards");
